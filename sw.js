// Damit die App auch ohne Netz aufgeht.
//
// Opa hat unterwegs nicht immer Empfang, und eine App, die dann eine
// Fehlerseite zeigt, ist eine kaputte App. Alles Noetige liegt deshalb
// lokal auf dem Geraet; das Netz wird nur benutzt, um nachzusehen,
// ob es etwas Neueres gibt.

const VERSION = "v9";
const CACHE = "opas-woche-" + VERSION;

const SHELL = [
  "./",
  "./index.html",
  "./manifest.webmanifest",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
  "./icons/apple-touch-icon.png",
  "./icons/favicon-32.png"
];

self.addEventListener("install", (e) => {
  e.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;

  // Die Seite selbst: erst nachsehen, ob es etwas Neueres gibt,
  // sonst die gespeicherte Fassung. So kommen Aenderungen an.
  if (req.mode === "navigate") {
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put("./index.html", copy));
          return res;
        })
        .catch(() => caches.match("./index.html"))
    );
    return;
  }

  // Alles andere (Icons, Schrift): erst lokal, sonst laden und behalten.
  e.respondWith(
    caches.match(req).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res && res.status === 200) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      }).catch(() => hit);
    })
  );
});
